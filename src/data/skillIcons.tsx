export function getSkillIcon(skill: string): IconType | null {
  const lower = skill.toLowerCase();
  for (const [keyword, Icon] of SKILL_ICONS) {
    if (lower.includes(keyword.toLowerCase())) return Icon;
  }
  return null;
}
