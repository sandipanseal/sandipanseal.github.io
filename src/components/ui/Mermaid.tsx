import { useEffect, useId, useState } from "react";

// Mermaid is large, so it is loaded only when a project page needs a diagram.
let ready: Promise<typeof import("mermaid").default> | null = null;
function loadMermaid() {
  ready ??= import("mermaid").then(({ default: mermaid }) => {
    mermaid.initialize({
      startOnLoad: false,
      securityLevel: "strict",
      theme: "base",
      themeVariables: {
        fontFamily: "Inter, system-ui, sans-serif",
        fontSize: "15px",
        primaryColor: "#1a2147",
        primaryTextColor: "#e8ecff",
        primaryBorderColor: "#6d8bff",
        lineColor: "#8aa2ff",
        secondaryColor: "#10131f",
        tertiaryColor: "#0a0c14",
        clusterBkg: "#0d1020",
        clusterBorder: "#3a4a8a",
        edgeLabelBackground: "#0a0c14",
        titleColor: "#e8ecff",
      },
      flowchart: { curve: "basis", htmlLabels: true, padding: 14, nodeSpacing: 36, rankSpacing: 44, wrappingWidth: 340 },
    });
    return mermaid;
  });
  return ready;
}

export default function Mermaid({ chart }: { chart: string }) {
  const id = "mmd" + useId().replace(/:/g, "");
  const [svg, setSvg] = useState("");
  const [failed, setFailed] = useState(false);

  useEffect(() => {
    let cancelled = false;
    setFailed(false);
    loadMermaid()
      .then((m) => m.render(id, chart))
      .then((r) => !cancelled && setSvg(r.svg))
      .catch(() => !cancelled && setFailed(true));
    return () => {
      cancelled = true;
    };
  }, [chart, id]);

  if (failed) return <p className="text-sm text-white/50">The diagram could not be rendered.</p>;
  if (!svg) return <p className="py-10 text-center text-sm text-white/40">Rendering diagram…</p>;
  // The SVG is generated by Mermaid (strict security level) from static strings in projectDetails.ts.
  return <div className="mermaid-diagram flex justify-center overflow-x-auto" dangerouslySetInnerHTML={{ __html: svg }} />;
}
